const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const deps=path.join(root,'.tools/powerbi/node_modules');
const vl=require(path.join(deps,'vega-lite'));
const Ajv=require(path.join(deps,'ajv'));
const schema=require(path.join(deps,'vega-lite/build/vega-lite-schema.json'));
const spec=JSON.parse(fs.readFileSync(path.join(root,'templates/deneb/vibe-retention-heatmap.json'),'utf8'));
const ajv=new Ajv({strict:false,allErrors:true});
ajv.addFormat('uri',value=>{try{return !!new URL(value).protocol;}catch{return false;}});
ajv.addFormat('uri-reference',value=>{try{return !!new URL(value,'https://example.com').href;}catch{return false;}});
ajv.addFormat('color-hex',/^#[0-9a-fA-F]{3}([0-9a-fA-F]{3})?$/);
const validator=ajv.compile(schema);
if(!validator(spec)) throw new Error(JSON.stringify(validator.errors));
const warnings=[];
const result=vl.compile(spec,{logger:{warn:(...v)=>warnings.push(v.join(' ')),info:()=>{},debug:()=>{},error:(...v)=>{throw new Error(v.join(' '))},level:()=>2}});
if(warnings.length) throw new Error(warnings.join('\n'));
fs.writeFileSync(path.join(root,'docs/vibe_dashboarding_test/deneb_validation.json'),JSON.stringify({status:'PASS',schema:spec.$schema,compiler:vl.version,warnings,compiledMarks:result.spec.marks.length,in_report_rendering:'NOT VERIFIED'},null,2)+'\n');
console.log('PASS: official Vega-Lite schema and compilation; in-report rendering NOT VERIFIED');
